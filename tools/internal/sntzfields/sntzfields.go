package sntzfields

import (
	"fmt"

	"github.com/sentinez/sentinez/api/gen/go/sentinez/types/common/v1"
	"github.com/sentinez/sentinez/tools/internal/utils"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
)

// GenerateSntzFieldsFile generates a _sntzfields.pb.go file containing gRPC service definitions.
func GenerateSntzFieldsFile(gen *protogen.Plugin, file *protogen.File) *protogen.GeneratedFile {
	filename := file.GeneratedFilenamePrefix + "_sntzfields.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-sntzfields. DO NOT EDIT.")
	g.P("// Copyright 2025 Duc-Hung Ho")
	g.P()

	g.P("package ", file.GoPackageName)
	g.P("\n")
	g.P("import (")
	g.P("\t\"fmt\"\n")
	g.P()
	g.P("\t\"github.com/sentinez/sentinez/api/gen/go/sentinez/types/common/v1\"\n")
	g.P(")")
	g.P("\n")
	g.P("var (")
	g.P("\t_ common.Empty")
	g.P("\t_ fmt.Stringer")
	g.P(")")
	g.P("\n")

	objectModelGen(g, file)
	return g
}

func objectModelGen(g *protogen.GeneratedFile, file *protogen.File) {
	for _, message := range file.Messages {
		opts := message.Desc.Options()

		ext, ok := proto.GetExtension(opts, common.E_SntzMsgOpts).(*common.SntzMsgOpts)
		if !ok || ext == nil {
			continue
		}

		if ext.GetExportField() {
			g.P("const (")
			for _, field := range message.Fields {
				fieldName := string(field.Desc.Name())
				constName := fmt.Sprintf("%sFields%s", message.GoIdent.GoName, utils.SnakeToPascal(fieldName))
				g.P(fmt.Sprintf("    %s = \"%s\"", constName, fieldName))
			}
			g.P(")")
			g.P("\n")
		}
	}
}
