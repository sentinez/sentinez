package code

import (
	"fmt"
	"strings"

	"github.com/common-nighthawk/go-figure"
	"google.golang.org/protobuf/compiler/protogen"
)

// GenerateFile generates a _sentinez.pb.go file containing gRPC service definitions.
func GenerateFile(gen *protogen.Plugin, file *protogen.File) *protogen.GeneratedFile {
	filename := file.GeneratedFilenamePrefix + "_sentinez.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)
	g.P("// Code generated by protoc-gen-go-sentinez. DO NOT EDIT.")
	g.P("// Copyright 2025 Duc-Hung Ho")
	g.P()

	g.P("package ", file.GoPackageName)
	g.P("\n")
	g.P("import (")
	g.P("\t\"fmt\"\n")
	g.P()
	g.P("\t\"github.com/sentinez/sentinez/api/gen/go/sentinez/common/v1\"\n")
	g.P(")")
	g.P("\n")
	g.P("var (")
	g.P("\t_ common.Empty")
	g.P("\t_ fmt.Stringer")
	g.P(")")
	g.P("\n")

	if !isFirstFileInPackage(gen, file) {
		return nil
	}

	ascii(g, file)
	return g
}

func ascii(g *protogen.GeneratedFile, file *protogen.File) {

	n := "SENTINEZ // " + strings.ToUpper(string(file.GoPackageName))
	asciiArt := figuregen(n, *file.Proto.Package)

	g.P("const ASCII = `\n", asciiArt, "`")
	g.P("\n")

	g.P("// PrintASCII the ASCII art to the console.")
	g.P("func PrintASCII() {")
	g.P("\tfmt.Print(ASCII)")
	g.P("}")
	g.P("\n")
}

func figuregen(header string, footer string) string {
	fig := figure.NewFigure("setnz", "speed", true)
	figureLines := strings.Split(fig.String(), "\n")
	sideText := []string{
		"",
		"",
		header,
		"------------",
		footer,
	}

	var v string
	for i, line := range figureLines {
		side := ""
		if i < len(sideText) {
			side = sideText[i]
		}
		v += fmt.Sprintf("%-40s %s\n", line, side)
	}

	return v
}

// isFirstFileInPackage returns true if the file is the first in its Go package.
func isFirstFileInPackage(gen *protogen.Plugin, file *protogen.File) bool {
	for _, f := range gen.Files {
		if f.GoImportPath == file.GoImportPath {
			return f == file
		}
	}
	return false
}
