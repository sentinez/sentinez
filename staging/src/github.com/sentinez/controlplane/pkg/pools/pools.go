// Package pools recycles the messages the collector decodes through the
// pools vtproto generates (the "pool" feature, see the generate.sh of the
// message): a message is reset when it goes back, keeping the capacity of
// its repeated fields. The pool of each message lives in its own package,
// e.g. pools/secrule.
package pools

// Message is the pointer to a message E that ReturnToVTPool resets and
// puts back in the vtproto pool of E.
type Message[E any] interface {
	*E
	ReturnToVTPool()
}

// Pool hands out the messages E of their vtproto pool.
type Pool[E any, P Message[E]] struct {
	get func() *E
}

// New returns the pool of E taking from get, the <E>FromVTPool function
// generated by vtproto, e.g. secrulepb.RuleEventFromVTPool.
func New[E any, P Message[E]](get func() *E) *Pool[E, P] {
	return &Pool[E, P]{get: get}
}

// Acquire returns a cleared message of the pool.
func (p *Pool[E, P]) Acquire() *E {
	return p.get()
}

// Release resets e and puts it back in the pool; e must not be used
// after.
func (*Pool[E, P]) Release(e *E) {
	P(e).ReturnToVTPool()
}

// NewBatch returns an empty batch of the pool, sized for n messages.
func (p *Pool[E, P]) NewBatch(n int) *Batch[E, P] {
	return &Batch[E, P]{items: make([]*E, 0, n)}
}

// Batch holds messages of a pool until Close releases them all.
type Batch[E any, P Message[E]] struct {
	items []*E
}

// Add appends e to the batch, which releases it on Close.
func (b *Batch[E, P]) Add(e *E) {
	b.items = append(b.items, e)
}

// Items the messages of the batch, valid until Close.
func (b *Batch[E, P]) Items() []*E {
	return b.items
}

// Close releases the messages of the batch to their pool.
func (b *Batch[E, P]) Close() error {
	for _, e := range b.items {
		P(e).ReturnToVTPool()
	}
	b.items = nil

	return nil
}
